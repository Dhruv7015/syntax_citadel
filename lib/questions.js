export async function getQuestion(world, level, questionId) {
  const key = `${world}-${level}`;
  const loader = loaders[key];
  if (!loader) return null;
  const mod = await loader();
  return mod.default[questionId] ?? null;
}

export function toPublic(q) {
  const { answer, hints, ...safe } = q;
  return safe;
}
